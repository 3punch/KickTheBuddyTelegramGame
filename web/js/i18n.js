let current = "en";

export function resolveLang(raw) {
  const code = String(raw || "").slice(0, 2).toLowerCase();
  return dict[code] ? code : "en";
}

export function setLang(code) {
  current = resolveLang(code);
  const meta = LANGS.find((l) => l.code === current) || LANGS[0];
  document.documentElement.lang = current;
  document.documentElement.dir = meta.rtl ? "rtl" : "ltr";
  return current;
}

export function getLang() {
  return current;
}

export function isRTL() {
  return (LANGS.find((l) => l.code === current) || {}).rtl === true;
}

export function t(key, vars) {
  const template = dict[current]?.[key] ?? dict.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name])
  );
}

export function fmt(n, lang = current) {
  try {
    return new Intl.NumberFormat(lang, { maximumFractionDigits: 0 }).format(Math.round(n || 0));
  } catch {
    return String(Math.round(n || 0));
  }
}

export function langLabel(code) {
  return (LANGS.find((l) => l.code === code) || LANGS[0]).label;
}

/** Apply data-i18n attributes across the document. */
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
}
